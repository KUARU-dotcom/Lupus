@dataclass
class Токен:
    """Представление одного токена."""
    тип: str
    значение: Any
    строка: int
    колонка: int


class Лексер:
    """Лексер для разбора исходного кода Lupus."""
    
    КЛЮЧЕВЫЕ_СЛОВА = {
        'define', 'define-mutable', 'set!', 'if', 'while',
        'list', 'nth', 'length', 'print', 'int->str',
        'quote', 'lambda', 'test'
    }
    
    def __init__(self, исходный_код: str):
        self.код = исходный_код
        self.позиция = 0
        self.строка = 1
        self.колонка = 1
        self.токены: List[Токен] = []
    
    def ошибка(self, сообщение: str) -> None:
        """Вывести ошибку лексера и выйти."""
        print(f"Ошибка лексера на строке {self.строка}, колонке {self.колонка}: {сообщение}")
        sys.exit(1)
    
    def текущий_символ(self) -> Optional[str]:
        """Получить текущий символ без продвижения."""
        if self.позиция >= len(self.код):
            return None
        return self.код[self.позиция]
    
    def следующий_символ(self) -> Optional[str]:
        """Получить следующий символ и продвинуться."""
        if self.позиция >= len(self.код):
            return None
        символ = self.код[self.позиция]
        self.позиция += 1
        if символ == '\n':
            self.строка += 1
            self.колонка = 1
        else:
            self.колонка += 1
        return символ
    
    def пропустить_пробелы_и_комментарии(self) -> None:
        """Пропустить пробелы и комментарии."""
        while self.позиция < len(self.код):
            символ = self.текущий_символ()
            
            # Пропускаем пробелы
            if символ and символ.isspace():
                self.следующий_символ()
            # Пропускаем комментарии
            elif (self.позиция + 1 < len(self.код) and
                  self.код[self.позиция:self.позиция+2] == ';;'):
                while (self.позиция < len(self.код) and
                       self.код[self.позиция] != '\n'):
                    self.следующий_символ()
            else:
                break
    
    def разобрать_строку(self) -> str:
        """Разобрать строку в двойных кавычках."""
        self.следующий_символ()  # пропустить открывающую кавычку
        значение = ''
        
        while self.позиция < len(self.код):
            символ = self.текущий_символ()
            
            if символ == '"':
                self.следующий_символ()
                return значение
            elif символ == '\\':
                self.следующий_символ()
                следующий = self.следующий_символ()
                if следующий == 'n':
                    значение += '\n'
                elif следующий == 't':
                    значение += '\t'
                elif следующий == '"':
                    значение += '"'
                elif следующий == '\\':
                    значение += '\\'
                else:
                    значение += следующий
            else:
                значение += self.следующий_символ()
        
        self.ошибка("Незакрытая строка")
    
    def разобрать_число(self) -> int:
        """Разобрать целое число."""
        значение = ''
        
        # Обработать минус
        if self.текущий_символ() == '-':
            значение += self.следующий_символ()
        
        while (self.позиция < len(self.код) and
               self.текущий_символ().isdigit()):
            значение += self.следующий_символ()
        
        return int(значение)
    
    def разобрать_символ(self) -> str:
        """Разобрать символ (имя переменной, оператор и т.д.)."""
        значение = ''
        
        while (self.позиция < len(self.код) and
               self.текущий_символ() not in '() \t\n;'):
            значение += self.следующий_символ()
        
        return значение
    
    def разобрать(self) -> List[Токен]:
        """Разобрать весь исходный код и вернуть список токенов."""
        while self.позиция < len(self.код):
            self.пропустить_пробелы_и_комментарии()
            
            if self.позиция >= len(self.код):
                break
            
            строка = self.строка
            колонка = self.колонка
            символ = self.текущий_символ()
            
            if символ == '(':
                self.следующий_символ()
                self.токены.append(Токен('LPAREN', '(', строка, колонка))
            
            elif символ == ')':
                self.следующий_символ()
                self.токены.append(Токен('RPAREN', ')', строка, колонка))
            
            elif символ == '"':
                значение = self.разобрать_строку()
                self.токены.append(Токен('STRING', значение, строка, колонка))
            
            elif символ == '-' and (self.позиция + 1 < len(self.код) and
                                     self.код[self.позиция + 1].isdigit()):
                значение = self.разобрать_число()
                self.токены.append(Токен('NUMBER', значение, строка, колонка))
            
            elif символ.isdigit():
                значение = self.разобрать_число()
                self.токены.append(Токен('NUMBER', значение, строка, колонка))
            
            else:
                значение = self.разобрать_символ()
                self.токены.append(Токен('SYMBOL', значение, строка, колонка))
        
        return self.токены


