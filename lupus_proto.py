class АСТ:
    """Базовый класс для узлов абстрактного синтаксического дерева."""
    pass


@dataclass
class АСТЧисло(АСТ):
    """Числовой литерал."""
    значение: int


@dataclass
class АСТСтрока(АСТ):
    """Строковый литерал."""
    значение: str


@dataclass
class АСТСимвол(АСТ):
    """Символ (переменная или имя функции)."""
    имя: str


@dataclass
class АСТСписок(АСТ):
    """Список форм (обычно - вызов функции)."""
    элементы: List[АСТ]


class Парсер:
    """Парсер для преобразования токенов в АСТ."""
    
    def __init__(self, токены: List[Токен]):
        self.токены = токены
        self.позиция = 0
    
    def ошибка(self, сообщение: str) -> None:
        """Вывести ошибку парсера и выйти."""
        if self.позиция < len(self.токены):
            токен = self.токены[self.позиция]
            print(f"Ошибка парсера на строке {токен.строка}, колонке {токен.колонка}: {сообщение}")
        else:
            print(f"Ошибка парсера: {сообщение}")
        sys.exit(1)
    
    def текущий_токен(self) -> Optional[Токен]:
        """Получить текущий токен."""
        if self.позиция >= len(self.токены):
            return None
        return self.токены[self.позиция]
    
    def следующий_токен(self) -> Optional[Токен]:
        """Получить текущий токен и продвинуться."""
        токен = self.текущий_токен()
        self.позиция += 1
        return токен
    
    def разобрать_форму(self) -> Optional[АСТ]:
        """Разобрать одну форму."""
        токен = self.текущий_токен()
        
        if токен is None:
            return None
        
        if токен.тип == 'NUMBER':
            self.следующий_токен()
            return АСТЧисло(токен.значение)
        
        elif токен.тип == 'STRING':
            self.следующий_токен()
            return АСТСтрока(токен.значение)
        
        elif токен.тип == 'SYMBOL':
            self.следующий_токен()
            return АСТСимвол(токен.значение)
        
        elif токен.тип == 'LPAREN':
            self.следующий_токен()
            элементы = []
            
            while True:
                текущий = self.текущий_токен()
                if текущий is None:
                    self.ошибка("Неожиданный конец файла: ожидалась закрывающая скобка")
                
                if текущий.тип == 'RPAREN':
                    self.следующий_токен()
                    break
                
                форма = self.разобрать_форму()
                if форма is not None:
                    элементы.append(форма)
            
            return АСТСписок(элементы)
        
        else:
            self.ошибка(f"Неожиданный токен: {токен.тип}")
    
    def разобрать(self) -> List[АСТ]:
        """Разобрать весь файл и вернуть список форм верхнего уровня."""
        формы = []
        
        while self.позиция < len(self.токены):
            форма = self.разобрать_форму()
            if форма is not None:
                формы.append(форма)
        
        return формы


