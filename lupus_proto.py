class Окружение:
    """Окружение переменных с поддержкой вложенных областей видимости."""
    
    def __init__(self, родитель: Optional['Окружение'] = None):
        self.родитель = родитель
        self.связи: Dict[str, Tuple[Any, bool]] = {}  # (значение, изменяемо)
    
    def определить(self, имя: str, значение: Any, изменяемо: bool = False) -> None:
        """Определить новую переменную в текущем окружении."""
        self.связи[имя] = (значение, изменяемо)
    
    def получить(self, имя: str) -> Any:
        """Получить значение переменной."""
        if имя in self.связи:
            return self.связи[имя][0]
        
        if self.родитель is not None:
            return self.родитель.получить(имя)
        
        raise NameError(f"Переменная не определена: {имя}")
    
    def установить(self, имя: str, значение: Any) -> None:
        """Установить значение переменной (только если она изменяемо)."""
        if имя in self.связи:
            старое_значение, изменяемо = self.связи[имя]
            if not изменяемо:
                raise NameError(f"Переменная {имя} не изменяемо")
            self.связи[имя] = (значение, изменяемо)
            return
        
        if self.родитель is not None:
            self.родитель.установить(имя, значение)
            return
        
        raise NameError(f"Переменная не определена: {имя}")


class Функция:
    """Представление пользовательской функции."""
    
    def __init__(self, параметры: List[str], тело: 'АСТ', закрытие: Окружение):
        self.параметры = параметры
        self.тело = тело
        self.закрытие = закрытие


class Интерпретатор:
    """Интерпретатор языка Lupus."""
    
    def __init__(self):
        self.глобальное_окружение = Окружение()
    
    def ошибка(self, сообщение: str) -> None:
        """Вывести ошибку и выйти."""
        print(f"Ошибка выполнения: {сообщение}")
        sys.exit(1)
    
    def вычислить(self, форма: АСТ, окружение: Окружение) -> Any:
        """Вычислить форму в контексте окружения."""
        
        if isinstance(форма, АСТЧисло):
            return форма.значение
        
        elif isinstance(форма, АСТСтрока):
            return форма.значение
        
        elif isinstance(форма, АСТСимвол):
            try:
                return окружение.получить(форма.имя)
            except NameError as e:
                self.ошибка(str(e))
        
        elif isinstance(форма, АСТСписок):
            if not форма.элементы:
                return None
            
            первый = форма.элементы[0]
            остаток = форма.элементы[1:]
            
            # Специальные формы
            if isinstance(первый, АСТСимвол):
                имя = первый.имя
                
                # (define имя значение)
                # (define (имя параметры...) тело)
                if имя == 'define':
                    if len(остаток) < 2:
                        self.ошибка("(define ...) требует минимум 2 аргумента")
                    
                    первый_арг = остаток[0]
                    
                    if isinstance(первый_арг, АСТСимвол):
                        # (define имя значение)
                        имя_переменной = первый_арг.имя
                        значение = self.вычислить(остаток[1], окружение)
                        окружение.определить(имя_переменной, значение, False)
                        return None
                    
                    elif isinstance(первый_арг, АСТСписок):
                        # (define (имя параметры...) тело...)
                        если_элементы = первый_арг.элементы
                        if not если_элементы:
                            self.ошибка("Пустой список в определении функции")
                        
                        имя_функции = если_элементы[0]
                        параметры = если_элементы[1:]
                        
                        if not isinstance(имя_функции, АСТСимвол):
                            self.ошибка("Имя функции должно быть символом")
                        
                        имя_функции = имя_функции.имя
                        имена_параметров = []
                        
                        for пар in параметры:
                            if not isinstance(пар, АСТСимвол):
                                self.ошибка("Параметры должны быть символами")
                            имена_параметров.append(пар.имя)
                        
                        # Тело функции - это все оставшиеся аргументы после списка параметров
                        # остаток[0] - список (имя пар...), остаток[1:] - тело
                        if len(остаток) < 2:
                            self.ошибка("Определение функции требует тела")
                        
                        if len(остаток) == 2:
                            тело = остаток[1]
                        else:
                            # Несколько форм в теле — оборачиваем в синтетический begin
                            тело = АСТСписок([АСТСимвол('begin')] + остаток[1:])
                        
                        функция = Функция(имена_параметров, тело, окружение)
                        окружение.определить(имя_функции, функция, False)
                        return None
                    
                    else:
                        self.ошибка("Некорректное определение переменной")
                
                # (define-mutable имя значение)
                elif имя == 'define-mutable':
                    if len(остаток) != 2:
                        self.ошибка("(define-mutable ...) требует ровно 2 аргумента")
                    
                    имя_переменной = остаток[0]
                    if not isinstance(имя_переменной, АСТСимвол):
                        self.ошибка("Первый аргумент define-mutable должен быть символом")
                    
                    имя_переменной = имя_переменной.имя
                    значение = self.вычислить(остаток[1], окружение)
                    окружение.определить(имя_переменной, значение, True)
                    return None
                
                # (set! имя значение)
                elif имя == 'set!':
                    if len(остаток) != 2:
                        self.ошибка("(set! ...) требует ровно 2 аргумента")
                    
                    имя_переменной = остаток[0]
                    if not isinstance(имя_переменной, АСТСимвол):
                        self.ошибка("Первый аргумент set! должен быть символом")
                    
                    имя_переменной = имя_переменной.имя
                    новое_значение = self.вычислить(остаток[1], окружение)
                    
                    try:
                        окружение.установить(имя_переменной, новое_значение)
                    except NameError as e:
                        self.ошибка(str(e))
                    
                    return None
                
                # (if условие то-ветвь иначе-ветвь)
                # (lambda (params...) body...)
                elif имя == 'lambda':
                    if len(остаток) < 2:
                        self.ошибка('(lambda ...) требует параметры и тело')
                    список_параметров = остаток[0]
                    if not isinstance(список_параметров, АСТСписок):
                        self.ошибка('Первый аргумент lambda должен быть списком параметров')
                    имена_параметров = []
                    for п in список_параметров.элементы:
                        if not isinstance(п, АСТСимвол):
                            self.ошибка('Параметры lambda должны быть символами')
                        имена_параметров.append(п.имя)
                    if len(остаток) == 2:
                        тело = остаток[1]
                    else:
                        тело = АСТСписок([АСТСимвол('begin')] + остаток[1:])
                    return Функция(имена_параметров, тело, окружение)

                elif имя == 'if':
                    if len(остаток) != 3:
                        self.ошибка("(if ...) требует ровно 3 аргумента")
                    
                    условие = self.вычислить(остаток[0], окружение)
                    
                    # В Lupus #t и #f используются, но мы используем Python bool
                    if условие:
                        return self.вычислить(остаток[1], окружение)
                    else:
                        return self.вычислить(остаток[2], окружение)
                
                # (while условие тело...)
                elif имя == 'while':
                    if len(остаток) < 2:
                        self.ошибка("(while ...) требует минимум 2 аргумента")
                    
                    условие_форма = остаток[0]
                    тело_формы = остаток[1:]
                    
                    результат = None
                    while True:
                        условие = self.вычислить(условие_форма, окружение)
                        if not условие:
                            break
                        
                        for форма_тела in тело_формы:
                            результат = self.вычислить(форма_тела, окружение)
                    
                    return результат
                
                # (print строка)
                elif имя == 'print':
                    if len(остаток) != 1:
                        self.ошибка("(print ...) требует ровно 1 аргумент")
                    
                    значение = self.вычислить(остаток[0], окружение)
                    
                    if not isinstance(значение, str):
                        self.ошибка("print требует строкового аргумента")
                    
                    print(значение)
                    return None
                
                # (int->str число)
                elif имя == 'int->str':
                    if len(остаток) != 1:
                        self.ошибка("(int->str ...) требует ровно 1 аргумент")
                    
                    значение = self.вычислить(остаток[0], окружение)
                    
                    if not isinstance(значение, int):
                        self.ошибка("int->str требует целого числа")
                    
                    return str(значение)
                
                # (string-append строка1 строка2 ...)
                elif имя == 'string-append':
                    результат = ''
                    for форма in остаток:
                        значение = self.вычислить(форма, окружение)
                        if not isinstance(значение, str):
                            self.ошибка('string-append требует строковых аргументов')
                        результат += значение
                    return результат

                # (list элем...)
                elif имя == 'list':
                    элементы = []
                    for форма in остаток:
                        элементы.append(self.вычислить(форма, окружение))
                    return элементы
                
                # (nth список индекс)
                elif имя == 'nth':
                    if len(остаток) != 2:
                        self.ошибка("(nth ...) требует ровно 2 аргумента")
                    
                    список = self.вычислить(остаток[0], окружение)
                    индекс = self.вычислить(остаток[1], окружение)
                    
                    if not isinstance(список, list):
                        self.ошибка("Первый аргумент nth должен быть списком")
                    if not isinstance(индекс, int):
                        self.ошибка("Второй аргумент nth должен быть целым числом")
                    
                    if индекс < 0 or индекс >= len(список):
                        self.ошибка(f"Индекс вне диапазона: {индекс}")
                    
                    return список[индекс]
                
                # (length список)
                elif имя == 'length':
                    if len(остаток) != 1:
                        self.ошибка("(length ...) требует ровно 1 аргумент")
                    
                    список = self.вычислить(остаток[0], окружение)
                    
                    if not isinstance(список, list):
                        self.ошибка("length требует списка")
                    
                    return len(список)
                
                # Операторы сравнения
                elif имя == '=':
                    if len(остаток) != 2:
                        self.ошибка("(= ...) требует ровно 2 аргумента")
                    левый = self.вычислить(остаток[0], окружение)
                    правый = self.вычислить(остаток[1], окружение)
                    return левый == правый
                
                elif имя == '!=':
                    if len(остаток) != 2:
                        self.ошибка("(!= ...) требует ровно 2 аргумента")
                    левый = self.вычислить(остаток[0], окружение)
                    правый = self.вычислить(остаток[1], окружение)
                    return левый != правый
                
                elif имя == '<':
                    if len(остаток) != 2:
                        self.ошибка("(< ...) требует ровно 2 аргумента")
                    левый = self.вычислить(остаток[0], окружение)
                    правый = self.вычислить(остаток[1], окружение)
                    if not isinstance(левый, int) or not isinstance(правый, int):
                        self.ошибка("< требует целых чисел")
                    return левый < правый
                
                elif имя == '>':
                    if len(остаток) != 2:
                        self.ошибка("(> ...) требует ровно 2 аргумента")
                    левый = self.вычислить(остаток[0], окружение)
                    правый = self.вычислить(остаток[1], окружение)
                    if not isinstance(левый, int) or not isinstance(правый, int):
                        self.ошибка("> требует целых чисел")
                    return левый > правый
                
                elif имя == '<=':
                    if len(остаток) != 2:
                        self.ошибка("(<= ...) требует ровно 2 аргумента")
                    левый = self.вычислить(остаток[0], окружение)
                    правый = self.вычислить(остаток[1], окружение)
                    if not isinstance(левый, int) or not isinstance(правый, int):
                        self.ошибка("<= требует целых чисел")
                    return левый <= правый
                
                elif имя == '>=':
                    if len(остаток) != 2:
                        self.ошибка("(>= ...) требует ровно 2 аргумента")
                    левый = self.вычислить(остаток[0], окружение)
                    правый = self.вычислить(остаток[1], окружение)
                    if not isinstance(левый, int) or not isinstance(правый, int):
                        self.ошибка(">= требует целых чисел")
                    return левый >= правый
                
                # (and форма1 форма2 ...) — короткое замыкание
                elif имя == 'and':
                    for форма in остаток:
                        значение = self.вычислить(форма, окружение)
                        if not значение:
                            return False
                    return True

                # (or форма1 форма2 ...) — короткое замыкание
                elif имя == 'or':
                    for форма in остаток:
                        значение = self.вычислить(форма, окружение)
                        if значение:
                            return True
                    return False

                # (not форма)
                elif имя == 'not':
                    if len(остаток) != 1:
                        self.ошибка('(not ...) требует ровно 1 аргумент')
                    return not self.вычислить(остаток[0], окружение)

                # Арифметические операторы
                elif имя == '+':
                    результат = 0
                    for форма in остаток:
                        значение = self.вычислить(форма, окружение)
                        if not isinstance(значение, int):
                            self.ошибка("+ требует целых чисел")
                        результат += значение
                    return результат
                
                elif имя == '-':
                    if not остаток:
                        self.ошибка("(-) требует минимум 1 аргумента")
                    
                    если_один_аргумент = len(остаток) == 1
                    if если_один_аргумент:
                        значение = self.вычислить(остаток[0], окружение)
                        if not isinstance(значение, int):
                            self.ошибка("- требует целых чисел")
                        return -значение
                    else:
                        первый = self.вычислить(остаток[0], окружение)
                        if not isinstance(первый, int):
                            self.ошибка("- требует целых чисел")
                        результат = первый
                        for форма in остаток[1:]:
                            значение = self.вычислить(форма, окружение)
                            if not isinstance(значение, int):
                                self.ошибка("- требует целых чисел")
                            результат -= значение
                        return результат
                
                elif имя == '*':
                    результат = 1
                    for форма in остаток:
                        значение = self.вычислить(форма, окружение)
                        if not isinstance(значение, int):
                            self.ошибка("* требует целых чисел")
                        результат *= значение
                    return результат
                
                elif имя == '/':
                    if len(остаток) != 2:
                        self.ошибка("(/ ...) требует ровно 2 аргумента")
                    
                    делимое = self.вычислить(остаток[0], окружение)
                    делитель = self.вычислить(остаток[1], окружение)
                    
                    if not isinstance(делимое, int) or not isinstance(делитель, int):
                        self.ошибка("/ требует целых чисел")
                    
                    if делитель == 0:
                        self.ошибка("Деление на ноль")
                    
                    return делимое // делитель

                # (% делимое делитель)
                elif имя == '%':
                    if len(остаток) != 2:
                        self.ошибка('(% ...) требует ровно 2 аргумента')
                    делимое = self.вычислить(остаток[0], окружение)
                    делитель = self.вычислить(остаток[1], окружение)
                    if not isinstance(делимое, int) or not isinstance(делитель, int):
                        self.ошибка('% требует целых чисел')
                    if делитель == 0:
                        self.ошибка('Деление на ноль')
                    return делимое % делитель

                # (test ...) - игнорируем для прототипа
                elif имя == 'test':
                    return None
                
                # (begin форма1 форма2 ...) - выполнить последовательность форм
                elif имя == 'begin':
                    результат = None
                    for форма in остаток:
                        результат = self.вычислить(форма, окружение)
                    return результат
                
                # Вызов пользовательской функции
                else:
                    функция = self.вычислить(первый, окружение)
                    
                    if isinstance(функция, Функция):
                        если_неправильное_количество = len(остаток) != len(функция.параметры)
                        if если_неправильное_количество:
                            self.ошибка(
                                f"Функция {имя} ожидает {len(функция.параметры)} "
                                f"аргументов, получено {len(остаток)}"
                            )
                        
                        # Вычислить аргументы
                        аргументы = []
                        for форма in остаток:
                            аргументы.append(self.вычислить(форма, окружение))
                        
                        # Создать новое окружение для функции
                        новое_окружение = Окружение(функция.закрытие)
                        
                        for имя_пар, значение_арг in zip(функция.параметры, аргументы):
                            новое_окружение.определить(имя_пар, значение_арг, False)
                        
                        # Вычислить тело функции
                        return self.вычислить(функция.тело, новое_окружение)
                    
                    else:
                        self.ошибка(f"Не могу вызвать не-функцию: {имя}")
            
            else:
                # Вычислить первый элемент
                функция = self.вычислить(первый, окружение)
                
                if isinstance(функция, Функция):
                    если_неправильное_количество = len(остаток) != len(функция.параметры)
                    if если_неправильное_количество:
                        self.ошибка(
                            f"Функция ожидает {len(функция.параметры)} "
                            f"аргументов, получено {len(остаток)}"
                        )
                    
                    # Вычислить аргументы
                    аргументы = []
                    for форма in остаток:
                        аргументы.append(self.вычислить(форма, окружение))
                    
                    # Создать новое окружение для функции
                    новое_окружение = Окружение(функция.закрытие)
                    
                    for имя_пар, значение_арг in zip(функция.параметры, аргументы):
                        новое_окружение.определить(имя_пар, значение_арг, False)
                    
                    # Вычислить тело функции
                    return self.вычислить(функция.тело, новое_окружение)
                
                else:
                    self.ошибка("Не могу вызвать не-функцию")
        
        self.ошибка(f"Не могу вычислить форму: {форма}")
    
    def выполнить(self, исходный_код: str) -> None:
        """Выполнить исходный код."""
        # Лексический анализ
        лексер = Лексер(исходный_код)
        токены = лексер.разобрать()
        
        # Синтаксический анализ
        парсер = Парсер(токены)
        формы = парсер.разобрать()
        
        # Выполнение
        for форма in формы:
            результат = self.вычислить(форма, self.глобальное_окружение)


