def главная():
    """Главная функция."""
    if len(sys.argv) == 1:
        # REPL режим
        цикл_repl()
    elif len(sys.argv) == 2:
        # Режим файла
        имя_файла = sys.argv[1]
        интерпретатор = Интерпретатор()
        
        try:
            with open(имя_файла, 'r', encoding='utf-8') as файл:
                исходный_код = файл.read()
            интерпретатор.выполнить(исходный_код)
        except FileNotFoundError:
            print(f"Ошибка: файл не найден: {имя_файла}")
            sys.exit(1)
    else:
        print("Использование: python lupus_proto.py [имя_файла]")
        sys.exit(1)


def цикл_repl():
    """Интерактивный режим REPL."""
    интерпретатор = Интерпретатор()
    
    print("Lupus Alpha v0.1 - REPL")
    print("Введите выражение Lupus или 'выход' для завершения")
    print()
    
    while True:
        try:
            строка = input("lupus> ")
        except EOFError:
            print()
            break
        
        if строка.lower() in ['выход', 'exit', 'quit']:
            break
        
        if not строка.strip():
            continue
        
        try:
            лексер = Лексер(строка)
            токены = лексер.разобрать()
            парсер = Парсер(токены)
            формы = парсер.разобрать()
            for форма in формы:
                рез = интерпретатор.вычислить(форма, интерпретатор.глобальное_окружение)
                if рез is not None:
                    print(рез)
        except (SyntaxError, NameError, ValueError, TypeError, ZeroDivisionError) as e:
            print(f"Ошибка: {e}")


if __name__ == '__main__':
    главная()
